package tool

// InvestigationMethod 是与领域无关的排障方法论，由 deep_investigate 子 agent、investigation 工具描述
// 与启用台账时的主 agent 系统提示共享；只写通用规则，领域知识留给 skill。
const InvestigationMethod = `## 通用排障方法（适用于任何系统）
1. 逐层追问"为什么"，停在系统之外的状态变化上：看到失败后问"它为什么失败"，得到答案再问一次，直到答案是一个外部变化（部署/升级、配置或文件被改、进程被中断、依赖到期或变更、资源耗尽、人为操作）。系统自身的保护、重试、降级、计数器、熔断只是机制（mechanism），它解释"问题如何表现"，不解释"问题为何开始"，不能当根因。
2. 用长时间窗找转折点：先把窗口放宽到数天，找到第一次失败（onset）和它之前的最后一次成功（last_good），两者都要有工具原文支撑；然后只问一个问题——这两个时间点之间发生了什么变化。手头日志里最早的一条失败不等于 onset。
3. 在能区分的层做对照：对照不是比较症状本身（坏的对象当然有报错），而是比较导致症状的那一层——同一份配置/文件/版本/依赖/调用参数，在正常对象（或正常时段）与故障对象上是否不同。两边都有的现象要排除。
4. 查附近最近被改过的东西：在故障组件的目录、配置、状态/缓存、补丁、依赖上按修改时间倒序看，最近的修改往往就是变化本身；工具失败或超时不代表"没有"，缩小范围重查。有健康对象时用 fs_compare 对比两边目录：哪边独有的文件、哪些文件在故障对象上停止更新。
5. 先验证历史案例：set_symptom 或 case_library 召回了相似案例时，先在本目标上执行案例的验证探针，用 from_case 记录假设并确认或排除，再做开放式调查。
6. 追到缺失信号的产生者：结论是"X 没有出现/没有发生"（文件、日志、回调、就绪标记）时，找到负责产生 X 的组件，读它自己的日志或状态，证据用 producer=true 记录；不要站在等待 X 的一方猜原因。
7. 失败形式变了就再找一次变化：问题窗口内报错、超时时长或表现形式发生变化，说明又有东西变了。在那个时间点查配置/参数/运维操作（timeline 的 change_sources、field_history 查参数取值历史），不能只说"根因相同"。
8. 数字先查含义再解释：把某个数字说成错误码/状态码之前，先用代码或文档确认它的定义；日志里的数字也可能是版本号、ID 或计数。
结论必须写成链条：外部变化(root) → 触发条件(trigger) → 系统机制(mechanism) → 症状，每一环都要有证据；缺哪一环就继续查哪一环。`
